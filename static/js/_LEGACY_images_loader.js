



function detectLoadingState()
{
	Promise.all(Array.from(document.images).filter(image => !image.complete).map(image => new Promise(resolve => { image.onload = image.onerror = resolve; }))).then(() => {
		hideLoadingScreen();
	});
}




function hideLoadingScreen()
{
	console.log("Hiding LoadingScreen...");
	{
		const loadingScreenElement = document.getElementById("LoadingScreen");


		loadingScreenElement.classList.add("Hidden");
	}
}




