



var visibleNavigationBar = false;




function setNavigationBar(visible)
{
	visibleNavigationBar = visible;
	applyNavigationBarVisibility();
}


function toggleNavigationBar()
{
	visibleNavigationBar = !visibleNavigationBar;
	applyNavigationBarVisibility();
}




function applyNavigationBarVisibility()
{
	const navigationBarElement = document.getElementById("NavigationBar");
	const navigationTogglerElement = document.getElementById("NavigationToggler");


	if (visibleNavigationBar) {
		console.log(`Setting navigation bar as visible...`);
		{
			navigationBarElement.classList.add("Shown");
			navigationTogglerElement.classList.add("Shown");
		}
	}
	else {
		console.log(`Setting navigation bar as invisible...`);
		{
			navigationBarElement.classList.remove("Shown");
			navigationTogglerElement.classList.remove("Shown");
		}
	}
}




