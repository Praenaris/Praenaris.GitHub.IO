



function removeWhitespaces()
{
	console.log("Removing whitespaces...");
	{
		let treeWalker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
		let whitespaceNodes = [];

		let currentTextNode;
		while (currentTextNode = treeWalker.nextNode()) {
			if (!currentTextNode.textContent.trim()) {
				whitespaceNodes.push(currentTextNode);
			}
		}

		whitespaceNodes.forEach((node) => node.parentNode.removeChild(node));
	}
}




